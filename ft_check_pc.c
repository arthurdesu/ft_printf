#include "ft_printf.h"

void	ft_check_pc(char c1, int *rtn, va_list *args)
{
	char	c2;

	if (c1 == '%')
	{
		write(1, "%", 1);
		*rtn += 1;
	}
	else if (c1 == 'c')
	{
		c2 = va_arg(*args, int);
		write(1, &c2, 1);
		*rtn += 1;
	}
}
